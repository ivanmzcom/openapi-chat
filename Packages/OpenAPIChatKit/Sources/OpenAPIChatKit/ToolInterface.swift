import Foundation
import FoundationModels

/// Where a tool argument ends up in the HTTP request.
public struct ToolArgumentBinding: Sendable {
    public enum Target: Sendable {
        case parameter(APIParameter)
        case bodyProperty(String)
        case wholeBody
    }

    public var argumentName: String
    public var target: Target
    public var schema: NormalizedSchema
}

/// The model-facing signature of an operation: a flat argument object plus how to map it back.
public struct ToolInterface: Sendable {
    public var parameters: GenerationSchema
    public var bindings: [ToolArgumentBinding]

    public init(operation: APIOperation, spec: APISpec, maxDepth: Int = 3, maxProperties: Int = 16) throws {
        var converter = DynamicSchemaConverter(prefix: operation.id)
        var properties: [DynamicGenerationSchema.Property] = []
        var bindings: [ToolArgumentBinding] = []
        var used = Set<String>()

        func add(_ name: String, _ schema: NormalizedSchema, description: String?, required: Bool, target: ToolArgumentBinding.Target) {
            let argName = APISpec.uniqueID(name, used: &used)
            properties.append(converter.property(name: argName, schema: schema, description: description, optional: !required))
            bindings.append(ToolArgumentBinding(argumentName: argName, target: target, schema: schema))
        }

        for parameter in operation.parameters {
            var (schema, hints) = spec.normalize(parameter.schema, maxDepth: maxDepth, maxProperties: maxProperties)
            if hints.description == nil || parameter.description != nil { hints.description = parameter.description }
            let location = parameter.location == .query || parameter.location == .path ? nil : "(\(parameter.location.rawValue))"
            let description = [hints.text(), location].compactMap { $0 }.joined(separator: " ")
            add(parameter.name, schema, description: description.isEmpty ? nil : description,
                required: parameter.isRequired, target: .parameter(parameter))
        }

        if let body = operation.requestBody {
            let (schema, hints) = spec.normalize(body.schema, maxDepth: maxDepth, maxProperties: maxProperties)
            // Flatten object bodies into top-level arguments: small models fill flat schemas more reliably.
            if case .object(let bodyProperties, let required) = schema {
                for property in bodyProperties {
                    let name = used.contains(property.name) ? "body_\(property.name)" : property.name
                    add(name, property.schema, description: property.description,
                        required: body.isRequired && required.contains(property.name),
                        target: .bodyProperty(property.name))
                }
            } else {
                add("body", schema, description: body.description ?? hints.text(), required: body.isRequired, target: .wholeBody)
            }
        }

        let root = DynamicGenerationSchema(name: "\(operation.id)_arguments", properties: properties)
        self.parameters = try GenerationSchema(root: root, dependencies: [])
        self.bindings = bindings
    }

    /// Turns the arguments generated by the model into request inputs.
    public func requestInput(from arguments: JSONValue) -> RequestInput {
        var input = RequestInput()
        let values = arguments.objectValue ?? [:]
        var body: [String: JSONValue] = [:]
        for binding in bindings {
            guard let raw = values[binding.argumentName], !raw.isNull else { continue }
            if case .string(let s) = raw, s.isEmpty { continue }
            let value = binding.schema.coerce(raw)
            switch binding.target {
            case .parameter(let parameter): input.parameters.append((parameter, value))
            case .bodyProperty(let name): body[name] = value
            case .wholeBody: input.body = value
            }
        }
        if !body.isEmpty { input.body = .object(body) }
        return input
    }
}

private struct DynamicSchemaConverter {
    let prefix: String
    var counter = 0

    mutating func property(name: String, schema: NormalizedSchema, description: String?, optional: Bool) -> DynamicGenerationSchema.Property {
        DynamicGenerationSchema.Property(name: name, description: description, schema: convert(schema), isOptional: optional)
    }

    mutating func convert(_ schema: NormalizedSchema) -> DynamicGenerationSchema {
        switch schema {
        case .string(let enumValues?):
            return DynamicGenerationSchema(name: nextName(), anyOf: enumValues)
        case .string(nil), .any:
            return DynamicGenerationSchema(type: String.self)
        case .integer(let minimum, let maximum):
            var guides: [GenerationGuide<Int>] = []
            if let minimum, minimum.isFinite { guides.append(.minimum(Int(minimum))) }
            if let maximum, maximum.isFinite { guides.append(.maximum(Int(maximum))) }
            return DynamicGenerationSchema(type: Int.self, guides: guides)
        case .number(let minimum, let maximum):
            var guides: [GenerationGuide<Double>] = []
            if let minimum { guides.append(.minimum(minimum)) }
            if let maximum { guides.append(.maximum(maximum)) }
            return DynamicGenerationSchema(type: Double.self, guides: guides)
        case .boolean:
            return DynamicGenerationSchema(type: Bool.self)
        case .array(let items, let minItems, let maxItems):
            return DynamicGenerationSchema(arrayOf: convert(items), minimumElements: minItems, maximumElements: maxItems)
        case .object(let properties, let required):
            let converted = properties.map {
                property(name: $0.name, schema: $0.schema, description: $0.description, optional: !required.contains($0.name))
            }
            return DynamicGenerationSchema(name: nextName(), properties: converted)
        }
    }

    private mutating func nextName() -> String {
        counter += 1
        return "\(prefix)_t\(counter)"
    }
}

extension GeneratedContent {
    var jsonValue: JSONValue {
        switch kind {
        case .null: .null
        case .bool(let b): .bool(b)
        case .number(let n): .number(n)
        case .string(let s): .string(s)
        case .array(let elements): .array(elements.map(\.jsonValue))
        case .structure(let properties, _): .object(properties.mapValues(\.jsonValue))
        @unknown default: (try? JSONValue.parse(Data(jsonString.utf8))) ?? .null
        }
    }
}
